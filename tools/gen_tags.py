#!/usr/bin/env python3
"""Emit tags_gen.go covering both synchronized and built-in registries.

Usage: gen_tags.py <reports_dir> <server_jar> <out_dir>

Run after gen_protocol.py (it overwrites that script's tags_gen.go).

Tag data is never sourced from known packs -- the wiki is explicit that it
"must always be sent by the server in full" -- so tags on built-in registries
(item, block, ...) matter too: synchronized entries reference them (an
enchantment's supported_items is e.g. #minecraft:enchantable/mace). Omitting
them leaves unbound references and the client disconnects while resolving.
"""
import io
import json
import sys
import zipfile
from pathlib import Path

from gen_registry_nbt import SYNC_REGISTRIES

# Tag directories whose registry is built-in, mapped to the registry name in
# registries.json (which carries the numeric protocol IDs).
BUILTIN_TAG_DIRS = {
    "block": "minecraft:block",
    "item": "minecraft:item",
    "entity_type": "minecraft:entity_type",
    "fluid": "minecraft:fluid",
    "game_event": "minecraft:game_event",
    "point_of_interest_type": "minecraft:point_of_interest_type",
    "potion": "minecraft:potion",
}


def main() -> None:
    reports, jar, outdir = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
    z = zipfile.ZipFile(jar)
    inner = next(n for n in z.namelist() if n.startswith("META-INF/versions/") and n.endswith(".jar"))
    iz = zipfile.ZipFile(io.BytesIO(z.read(inner)))
    names = iz.namelist()

    # dir -> ordered entry names, and dir -> registry name.
    entries_by_dir: dict[str, list[str]] = {}
    registry_by_dir: dict[str, str] = {}
    for subdir, regname in SYNC_REGISTRIES.items():
        prefix = f"data/minecraft/{subdir}/"
        found = sorted(
            "minecraft:" + n[len(prefix) : -len(".json")]
            for n in names
            if n.startswith(prefix) and n.endswith(".json")
        )
        if found:
            entries_by_dir[subdir] = found
            registry_by_dir[subdir] = regname

    reg_json = json.loads((reports / "registries.json").read_text())
    for subdir, regname in BUILTIN_TAG_DIRS.items():
        entries = reg_json.get(regname, {}).get("entries", {})
        if entries:
            entries_by_dir[subdir] = [
                n for n, _ in sorted(entries.items(), key=lambda kv: kv[1]["protocol_id"])
            ]
            registry_by_dir[subdir] = regname

    tag_files = {
        n[len("data/minecraft/tags/") : -len(".json")]: n
        for n in names
        if n.startswith("data/minecraft/tags/") and n.endswith(".json")
    }

    def dir_of(rel: str):
        best = None
        for d in entries_by_dir:
            if rel == d or rel.startswith(d + "/"):
                if best is None or len(d) > len(best):
                    best = d
        return best

    def resolve(regdir, ids, value, seen):
        if isinstance(value, dict):
            value = value.get("id")
        if not isinstance(value, str):
            return []
        if value.startswith("#"):
            ref = value[1:]
            if ":" not in ref:
                ref = "minecraft:" + ref
            key = ref.split(":", 1)[1]
            full = f"{regdir}/{key}"
            if key in seen or full not in tag_files:
                return []
            seen.add(key)
            out = []
            for v in json.loads(iz.read(tag_files[full])).get("values", []):
                out += resolve(regdir, ids, v, seen)
            return out
        return [ids[value]] if value in ids else []

    grouped: dict[str, list] = {}
    for rel, path in sorted(tag_files.items()):
        regdir = dir_of(rel)
        if regdir is None:
            continue
        ids = {name: i for i, name in enumerate(entries_by_dir[regdir])}
        tag_path = rel[len(regdir) + 1 :]
        seen = {tag_path}
        vals, dedup = [], set()
        for v in json.loads(iz.read(path)).get("values", []):
            for i in resolve(regdir, ids, v, seen):
                if i not in dedup:
                    dedup.add(i)
                    vals.append(i)
        grouped.setdefault(registry_by_dir[regdir], []).append(("minecraft:" + tag_path, vals))

    out = [
        "// Code generated by tools/gen_tags.py. DO NOT EDIT.",
        "//",
        "// Tag members as raw registry IDs, expanded from the vanilla data pack",
        "// with nested #tag references resolved, for synchronized AND built-in",
        "// registries (tags are never sourced from known packs).",
        "",
        f"package {outdir.name}",
        "",
        "// RegistryTags maps registry -> tag -> ordered raw entry IDs.",
        "var RegistryTags = map[string]map[string][]int32{",
    ]
    total = 0
    for regname, tags in sorted(grouped.items()):
        out.append(f'\t"{regname}": {{')
        for tag_name, vals in tags:
            total += 1
            ids_str = ", ".join(map(str, vals))
            out.append(f'\t\t"{tag_name}": {{{ids_str}}},')
        out.append("\t},")
    out.append("}")
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "tags_gen.go").write_text("\n".join(out))
    print(f"wrote {outdir}/tags_gen.go: {len(grouped)} registries, {total} tags")


if __name__ == "__main__":
    main()

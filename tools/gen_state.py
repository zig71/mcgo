#!/usr/bin/env python3
"""Embeds the per-state tables a server needs that the game computes itself.

Five blobs, all indexed by block state id (or item id), all produced by running
the game — see tools/dump_light/DumpLight.java and DumpBreak.java:

  dampening.bin   the cost of a light step through the state
  emission.bin    the light the state gives off
  hardness.bin    the state's hardness, times a hundred, two bytes big-endian
  stateTools.bin  which probe tools harvest the state, bit 6 for "needs the tool"
  itemTools.bin   per item id: which probe blocks it is fast on, and its speed

None of them is in the data generator's block report: dampening comes from
per-state shapes, emission from getLightEmission, hardness from
getDestroySpeed, and the tool masks from isCorrectToolForDrops.

usage: gen_state.py <dir with the .bin files> <out dir> <package>

Pass "-" to emit empty tables: a version whose jar cannot be dumped this way
falls back to the hand-written tables and the opacity rule.
"""
import os
import sys


def main() -> None:
    src, outdir, package = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(outdir, exist_ok=True)

    def blob(name: str) -> bytes:
        if src == "-" or not os.path.exists(os.path.join(src, name)):
            return b""
        return open(os.path.join(src, name), "rb").read()

    blobs = [
        ("dampening.bin", "LightDampening", blob("dampening.bin"),
         ["LightDampening is the light cost of a step through each block state,",
          "indexed by state id: BlockStateBase.getLightDampening from the game",
          "itself. LightEngine.getOpacity floors a step at one."]),
        ("emission.bin", "LightEmission", blob("emission.bin"),
         ["LightEmission is the light each block state gives off, indexed by state",
          "id: getLightEmission from the game itself."]),
        ("hardness.bin", "BreakHardness", blob("hardness.bin"),
         ["BreakHardness is two bytes per block state, big-endian: the state's",
          "hardness times a hundred, from getDestroySpeed. -1 (times a hundred)",
          "means unbreakable."]),
        ("stateTools.bin", "BlockTools", blob("stateTools.bin"),
         ["BlockTools is one byte per block state: which of six probe tools harvest",
          "it, and bit 6 for requiresCorrectToolForDrops."]),
        ("itemTools.bin", "ItemTools", blob("itemTools.bin"),
         ["ItemTools is two bytes per item id: which probe blocks the item is fast",
          "on, and the destroy speed it reaches on them."]),
    ]

    lines = ["// Code generated by tools/gen_state.py. DO NOT EDIT.", "", f"package {package}", ""]
    if any(b for _, _, b, _ in blobs):
        lines += ['import _ "embed"', ""]
    for name, var, body, doc in blobs:
        if body:
            open(os.path.join(outdir, name), "wb").write(body)
            lines.append(f"//go:embed {name}")
        else:
            lines.append(f"// {var} is empty for this version: its jar does not carry")
            lines.append("// the classes these tables are dumped from, so the server falls")
            lines.append("// back to its hand-written tables.")
        lines += [f"// {d}" for d in doc]
        lines += [f"var {var} []byte", ""]
    open(os.path.join(outdir, "state_gen.go"), "w").write("\n".join(lines).rstrip() + "\n")

    sizes = ", ".join(f"{v}={len(b)}" for _, v, b, _ in blobs)
    print(f"wrote {outdir}/state_gen.go ({sizes})")


main()

#!/usr/bin/env python3
"""Generates name -> protocol id maps for the built-in registries.

The client knows these already (they are code-defined, not data-pack ones), so
they are never sent; but their ids are needed for the packets that reference
them by id, like the sound and particle a packet asks for.

usage: gen_builtin.py <reports dir> <out dir> <package>
"""
import json
import os
import sys


def main():
    reports, outdir, package = sys.argv[1], sys.argv[2], sys.argv[3]
    data = json.load(open(os.path.join(reports, "registries.json")))
    wanted = [
        "minecraft:sound_event",
        "minecraft:particle_type",
        "minecraft:recipe_display",
        "minecraft:slot_display",
        "minecraft:recipe_book_category",
        "minecraft:command_argument_type",
        "minecraft:stat_type",
        "minecraft:custom_stat",
        "minecraft:block",
    ]
    out = ["// Code generated by tools/gen_builtin.py. DO NOT EDIT.", "", "package " + package, ""]
    for registry in wanted:
        entries = data[registry]["entries"]
        ids = {}
        for name, info in entries.items():
            ids[name] = info["protocol_id"]
        var = "".join(p.capitalize() for p in registry.split(":")[1].split("_")) + "IDs"
        out.append("// %s maps %s names to their protocol ids." % (var, registry))
        out.append("var %s = map[string]int32{" % var)
        for name in sorted(ids, key=lambda n: ids[n]):
            out.append('\t"%s": %d,' % (name, ids[name]))
        out.append("}")
        out.append("")
    open(os.path.join(outdir, "builtin_gen.go"), "w").write("\n".join(out))
    print("wrote %s/builtin_gen.go" % outdir)


main()

#!/usr/bin/env python3
"""Emit the block-state lookup tables (blockstates.bin).

Usage: gen_blockstates.py <reports_dir> <out_dir>

Anvil chunk palettes name blocks ("minecraft:oak_stairs" + properties), while
the network format needs numeric block-state ids. Two tables bridge that:

  states: canonical "name[a=b,c=d]" -> id, for every state
  blocks: block name -> its default property list

The properties block matters because a palette entry may only list the
properties that differ from the default, so a lookup for a partial key is
completed from the defaults before retrying.

Binary layout, all big-endian:
  u32 count, then per entry: u32 id, u16 length, key bytes
  u32 count, then per entry: u16 length, block name, u16 length, default props
"""
import json
import struct
import sys
from pathlib import Path


def canon(props: dict) -> str:
    if not props:
        return ""
    return "[" + ",".join(f"{k}={props[k]}" for k in sorted(props)) + "]"


def main() -> None:
    reports, outdir = Path(sys.argv[1]), Path(sys.argv[2])
    blocks = json.loads((reports / "blocks.json").read_text())

    states = []
    defaults = []
    for name, d in blocks.items():
        entries = d.get("states") or []
        if not entries:
            continue
        default = next((s for s in entries if s.get("default")), entries[0])
        defaults.append((name, canon(default.get("properties") or {})))
        for st in entries:
            states.append((name + canon(st.get("properties") or {}), st["id"]))
    states.sort()

    out = bytearray()
    out += struct.pack(">I", len(states))
    for key, sid in states:
        b = key.encode("utf-8")
        out += struct.pack(">I", sid) + struct.pack(">H", len(b)) + b
    out += struct.pack(">I", len(defaults))
    for name, props in defaults:
        nb, pb = name.encode("utf-8"), props.encode("utf-8")
        out += struct.pack(">H", len(nb)) + nb + struct.pack(">H", len(pb)) + pb

    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "blockstates.bin").write_bytes(bytes(out))
    (outdir / "blockstates_gen.go").write_text(
        "// Code generated by tools/gen_blockstates.py. DO NOT EDIT.\n\n"
        f"package {outdir.name}\n\n"
        'import _ "embed"\n\n'
        "// BlockStates is states-then-defaults, described in gen_blockstates.py.\n"
        "//go:embed blockstates.bin\n"
        "var BlockStates []byte\n"
    )
    print(f"wrote {outdir}/blockstates.bin: {len(states)} states, {len(defaults)} blocks")


if __name__ == "__main__":
    main()

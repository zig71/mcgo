#!/usr/bin/env python3
"""Generate Go protocol tables from the vanilla server's own reports + data pack.

Usage: gen_protocol.py <reports_dir> <server_jar> <out_dir>

Inputs (authoritative, produced by the vanilla data generator):
  reports/packets.json   -- packet names -> protocol_id per state/direction
  server.jar             -- bundler; inner jar holds data/minecraft/<registry>/*.json

Outputs:
  packets_gen.go         -- packet ID constants per state/direction
  registries_gen.go      -- synchronized-registry entry name lists (ordered)
"""

def go_name(packet: str) -> str:
    p = packet.split(":", 1)[-1]
    return "".join(w.capitalize() for w in re.split(r"[^0-9a-zA-Z]+", p) if w)


def gen_packets(packets: dict, pkg: str) -> str:
    out = ["// Code generated by tools/gen_protocol.py. DO NOT EDIT.", "", f"package {pkg}", ""]
    for state in STATES:
        for direction in DIRECTIONS:
            entries = packets.get(state, {}).get(direction, {})
            if not entries:
                continue
            out.append(f"// {state} {direction}")
            out.append("const (")
            for name, info in sorted(entries.items(), key=lambda kv: kv[1]["protocol_id"]):
                ident = f"{state.capitalize()}{direction.capitalize()}{go_name(name)}"
                out.append(f"\t{ident} = {info['protocol_id']}")
            out.append(")")
            out.append("")
    return "\n".join(out)


def gen_registries(jar_path: str, pkg: str) -> str:
    z = zipfile.ZipFile(jar_path)
    inner = next(n for n in z.namelist() if n.startswith("META-INF/versions/") and n.endswith(".jar"))
    iz = zipfile.ZipFile(io.BytesIO(z.read(inner)))
    entries = {n for n in iz.namelist() if n.startswith("data/minecraft/") and n.endswith(".json")}

    out = [
        "// Code generated by tools/gen_protocol.py. DO NOT EDIT.",
        "//",
        "// Entry names per synchronized registry, in the order the server assigns",
        "// numeric IDs. Names only: NBT is omitted on the wire via known-pack",
        "// negotiation (client sources it from minecraft:core).",
        "",
        f"package {pkg}",
        "",
        "// RegistryEntries maps a registry name to its ordered entry names.",
        "var RegistryEntries = map[string][]string{",
    ]
    total = 0
    emitted = []
    for subdir, regname in SYNC_REGISTRIES.items():
        prefix = f"data/minecraft/{subdir}/"
        names = sorted(
            "minecraft:" + n[len(prefix) : -len(".json")] for n in entries if n.startswith(prefix)
        )
        if not names:
            continue
        emitted.append(regname)
        total += len(names)
        out.append(f'\t"{regname}": {{')
        for n in names:
            out.append(f'\t\t"{n}",')
        out.append("\t},")
    out.append("}")
    out.append("")
    out.append("// RegistryOrder is the order registries must be sent in.")
    out.append("//")
    out.append("// The client assigns registry IDs by the order it receives them, and tag")
    out.append("// entries are resolved against those IDs, so a different order points")
    out.append("// every tag at the wrong element. Measured against a real 26.3 server:")
    out.append("// it sends these in declaration order, not sorted.")
    out.append("var RegistryOrder = []string{")
    for name in emitted:
        out.append(f'\t"{name}",')
    out.append("}")
    out.append("")
    out.append(f"// Total registry entries: {total}")
    return "\n".join(out)


def gen_tags(jar_path: str, reports_dir: Path, pkg: str) -> str:
    z = zipfile.ZipFile(jar_path)
    inner = next(n for n in z.namelist() if n.startswith("META-INF/versions/") and n.endswith(".jar"))
    iz = zipfile.ZipFile(io.BytesIO(z.read(inner)))
    names = iz.namelist()

    # regdir -> (registry name, entry name -> raw ID). Synchronized registries
    # get IDs from their sorted data-pack entries, exactly as registry data is
    # sent. Built-in registries (block, item, ...) are fixed in the client and
    # their IDs are the protocol_ids in reports/registries.json; vanilla sends
    # their tags too, and the client relies on them (e.g. #minecraft:logs).
    registries = {}
    for subdir, regname in SYNC_REGISTRIES.items():
        prefix = f"data/minecraft/{subdir}/"
        entries = sorted(
            "minecraft:" + n[len(prefix) : -len(".json")] for n in names if n.startswith(prefix) and n.endswith(".json")
        )
        registries[subdir] = (regname, {name: i for i, name in enumerate(entries)})
    for regname, reg in json.loads(Path(reports_dir, "registries.json").read_text()).items():
        subdir = regname.split(":", 1)[1]
        if subdir not in registries:
            registries[subdir] = (regname, {k: v["protocol_id"] for k, v in reg["entries"].items()})

    tag_files = {
        n[len("data/minecraft/tags/") : -len(".json")]: n
        for n in names
        if n.startswith("data/minecraft/tags/") and n.endswith(".json")
    }

    def regdir_of(rel: str):
        best = None
        for sd in registries:
            if rel == sd or rel.startswith(sd + "/"):
                if best is None or len(sd) > len(best):
                    best = sd
        return best

    def resolve(regdir, ids, value, seen):
        if isinstance(value, dict):
            value = value.get("id")
        if not isinstance(value, str):
            return []
        if value.startswith("#"):
            ref = value[1:]
            if ":" not in ref:
                ref = "minecraft:" + ref
            key = ref.split(":", 1)[1]
            full = f"{regdir}/{key}"
            if key in seen or full not in tag_files:
                return []
            seen.add(key)
            out = []
            for v in json.loads(iz.read(tag_files[full])).get("values", []):
                out += resolve(regdir, ids, v, seen)
            return out
        return [ids[value]] if value in ids else []

    out = [
        "// Code generated by tools/gen_protocol.py. DO NOT EDIT.",
        "//",
        "// Tag members as raw registry IDs, expanded from the vanilla data pack",
        "// with nested #tag references resolved. Covers synchronized registries",
        "// and built-in ones (block, item, ...), matching vanilla's Update Tags.",
        "",
        f"package {pkg}",
        "",
        "// RegistryTags maps registry -> tag -> ordered raw entry IDs.",
        "var RegistryTags = map[string]map[string][]int32{",
    ]
    grouped = {}
    for rel, path in sorted(tag_files.items()):
        regdir = regdir_of(rel)
        if regdir is None:
            continue
        regname, ids = registries[regdir]
        tag_path = rel[len(regdir) + 1 :]
        seen = {tag_path}
        vals, dedup = [], set()
        for v in json.loads(iz.read(path)).get("values", []):
            for i in resolve(regdir, ids, v, seen):
                if i not in dedup:
                    dedup.add(i)
                    vals.append(i)
        grouped.setdefault(regname, []).append(("minecraft:" + tag_path, vals))

    for regname, tags in sorted(grouped.items()):
        out.append(f'\t"{regname}": {{')
        for tag_name, vals in tags:
            ids_str = ", ".join(map(str, vals))
            out.append(f'\t\t"{tag_name}": {{{ids_str}}},')
        out.append("\t},")
    out.append("}")
    return "\n".join(out)


# Default block-state IDs emitted for the flat world builder.
FLAT_BLOCKS = ["air", "bedrock", "dirt", "grass_block", "stone"]


def gen_blocks(blocks_json: str, pkg: str) -> str:
    data = json.loads(Path(blocks_json).read_text())
    out = [
        "// Code generated by tools/gen_protocol.py. DO NOT EDIT.",
        "//",
        "// Default block-state IDs from reports/blocks.json (state index 0).",
        "",
        f"package {pkg}",
        "",
        "const (",
    ]
    for b in FLAT_BLOCKS:
        ident = "Block" + "".join(w.capitalize() for w in b.split("_"))
        states = data["minecraft:" + b]["states"]
        default = next((s for s in states if s.get("default")), states[0])
        out.append(f'\t{ident} = {default["id"]}')
    out.append(")")
    return "\n".join(out)



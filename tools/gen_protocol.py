def main() -> None:
    reports, jar, outdir = sys.argv[1], sys.argv[2], Path(sys.argv[3])
    # The synchronized set comes from the data pack, not from the table below:
    # that table had drifted and was missing a third of the registries.
    SYNC_REGISTRIES.clear()
    SYNC_REGISTRIES.update(sync_registries_from_reports(Path(reports)))
    outdir.mkdir(parents=True, exist_ok=True)
    pkg = outdir.name
    packets = json.loads(Path(reports, "packets.json").read_text())
    (outdir / "packets_gen.go").write_text(gen_packets(packets, pkg))
    (outdir / "registries_gen.go").write_text(gen_registries(jar, pkg))
    (outdir / "tags_gen.go").write_text(gen_tags(jar, Path(reports), pkg))
    (outdir / "blocks_gen.go").write_text(gen_blocks(Path(reports, "blocks.json"), pkg))
    print(f"wrote {outdir}/packets_gen.go, registries_gen.go, tags_gen.go, blocks_gen.go")


if __name__ == "__main__":
    main()

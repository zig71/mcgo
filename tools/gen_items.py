#!/usr/bin/env python3
"""Emit the item -> default block state mapping (items_gen.go).

Usage: gen_items.py <reports_dir> <out_dir>

A held item's registry ID (what Set Creative Mode Slot carries) is not a block
state ID: items live in minecraft:item, block states in the block state
registry. Placing what the player holds needs the mapping, which is derivable
from the vanilla reports -- every item sharing a name with a block places that
block's default state.
"""
import json
import sys
from pathlib import Path

MODULE = "mcgo"


def main() -> None:
    reports, outdir = Path(sys.argv[1]), Path(sys.argv[2])
    blocks = json.loads((reports / "blocks.json").read_text())
    regs = json.loads((reports / "registries.json").read_text())

    items = regs.get("minecraft:item", {}).get("entries", {})
    mapping = {}
    for name, block in blocks.items():
        item = items.get(name)
        if not item:
            continue
        states = block.get("states") or []
        if not states:
            continue
        default = next((s for s in states if s.get("default")), states[0])
        mapping[item["protocol_id"]] = default["id"]

    out = [
        "// Code generated by tools/gen_items.py. DO NOT EDIT.",
        "//",
        "// Item registry ID -> the block state ID that item places.",
        "",
        f"package {outdir.name}",
        "",
        f'import "{MODULE}/internal/proto"',
        "",
        "// ItemBlockState maps a minecraft:item ID to the default block state it",
        "// places, for items that place a block.",
        "var ItemBlockState = map[int32]int32{",
    ]
    for item_id in sorted(mapping):
        out.append(f"\t{item_id}: {mapping[item_id]},")
    out.append("}")
    out.append("")
    out.append("// SignBlockStates lists the block state IDs whose block is a sign")
    out.append("// (any wood, wall or hanging variant): placing one opens the editor.")
    out.append("var SignBlockStates = map[int32]bool{")
    sign_ids = set()
    for name, block in blocks.items():
        if "_sign" not in name:
            continue
        for st in block.get("states") or []:
            sign_ids.add(st["id"])
    for sid in sorted(sign_ids):
        out.append(f"\t{sid}: true,")
    out.append("}")
    be = regs.get("minecraft:block_entity_type", {}).get("entries", {})
    sign_be = be.get("minecraft:sign", {}).get("protocol_id", 7)
    out.append("")
    out.append("// SignBlockEntityTypeID is minecraft:sign in the block_entity_type registry.")
    out.append(f"const SignBlockEntityTypeID = {sign_be}")
    out.append("")
    out.append("// ItemIDs maps an item name to its registry ID. The synchronized")
    out.append("// registry list does not include minecraft:item, which is built in, so")
    out.append("// name lookups need their own table.")
    out.append("var ItemIDs = map[string]int32{")
    for name in sorted(items):
        out.append(f'\t"{name}": {items[name]["protocol_id"]},')
    out.append("}")
    # Placement metadata: which block an item places, what properties that
    # block has, and whether it has a wall-mounted twin (a sign clicked onto a
    # wall becomes a wall sign, and the same is true of banners and torches).
    out.append("")
    out.append("// ItemBlockName maps an item to the block it places when used.")
    out.append("var ItemBlockName = map[int32]string{")
    for name, block in sorted(blocks.items()):
        item = items.get(name)
        if not item:
            continue
        out.append(f'\t{item["protocol_id"]}: "{name}",')
    out.append("}")
    out.append("")
    out.append("// BlockItems maps a block to the item that places it, so a block the")
    out.append("// player picks (middle-click) can be turned back into an item.")
    out.append("var BlockItems = map[string]int32{")
    for name in sorted(blocks):
        item = items.get(name)
        if not item:
            continue
        out.append(f'\t"{name}": {item["protocol_id"]},')
    out.append("}")
    out.append("")
    out.append("// BlockProps lists a block's property names, which is what decides")
    out.append("// how a placed block is oriented.")
    out.append("var BlockProps = map[string][]string{")
    for name, block in sorted(blocks.items()):
        props = sorted((block.get("properties") or {}).keys())
        if not props:
            continue
        joined = ", ".join(f'"{p}"' for p in props)
        out.append(f'\t"{name}": {{{joined}}},')
    out.append("}")
    out.append("")
    out.append("// WallVariant maps a block to the wall-mounted block a player gets")
    out.append("// when placing it against a vertical face (signs, banners, torches).")
    out.append("var WallVariant = map[string]string{")
    wall_pairs = []
    for name in blocks:
        short = name.split(":", 1)[1]
        cand = None
        if short.endswith("_sign"):
            cand = short[: -len("_sign")] + "_wall_sign"
        elif short.endswith("_banner"):
            cand = short[: -len("_banner")] + "_wall_banner"
        elif short in ("torch", "redstone_torch", "soul_torch"):
            cand = short.replace("torch", "wall_torch")
        if cand and ("minecraft:" + cand) in blocks:
            wall_pairs.append((name, "minecraft:" + cand))
    for a, b in sorted(wall_pairs):
        out.append(f'\t"{a}": "{b}",')
    out.append("}")
    out.append("")
    out.append("// SixWayFacing marks blocks whose facing property has up and down as")
    out.append("// well as the four horizontal directions.")
    out.append("var SixWayFacing = map[string]bool{")
    six = []
    for name, block in blocks.items():
        values = (block.get("properties") or {}).get("facing")
        if values and "up" in values and "north" in values:
            six.append(name)
    for name in sorted(six):
        out.append(f'\t"{name}": true,')
    out.append("}")
    # Which block state has a block entity, and which one. The order matters:
    # a hanging sign also ends in "_sign", and a trapped chest also ends in
    # "_chest", so the narrower families are matched first.
    be_types = {k[10:]: v["protocol_id"] for k, v in regs.get("minecraft:block_entity_type", {}).get("entries", {}).items()}
    be_patterns = [
        ("hanging_sign", "*_hanging_sign"),
        ("hanging_sign", "*_wall_hanging_sign"),
        ("sign", "*_sign"),
        ("banner", "*_banner"),
        ("banner", "*_wall_banner"),
        ("bed", "*_bed"),
        ("trapped_chest", "trapped_chest"),
        ("ender_chest", "ender_chest"),
        ("chest", "chest"),
        ("chest", "*_chest"),
        ("shulker_box", "shulker_box"),
        ("shulker_box", "*_shulker_box"),
        ("furnace", "furnace"),
        ("blast_furnace", "blast_furnace"),
        ("smoker", "smoker"),
        ("hopper", "hopper"),
        ("dispenser", "dispenser"),
        ("dropper", "dropper"),
        ("barrel", "barrel"),
        ("beacon", "beacon"),
        ("lectern", "lectern"),
        ("campfire", "campfire"),
        ("campfire", "soul_campfire"),
        ("brewing_stand", "brewing_stand"),
        ("enchanting_table", "enchanting_table"),
        ("jukebox", "jukebox"),
        ("conduit", "conduit"),
        ("bell", "bell"),
        ("beehive", "beehive"),
        ("beehive", "bee_nest"),
        ("chiseled_bookshelf", "chiseled_bookshelf"),
        ("shelf", "shelf"),
        ("decorated_pot", "decorated_pot"),
        ("sculk_sensor", "sculk_sensor"),
        ("calibrated_sculk_sensor", "calibrated_sculk_sensor"),
        ("sculk_catalyst", "sculk_catalyst"),
        ("sculk_shrieker", "sculk_shrieker"),
        ("brushable_block", "suspicious_sand"),
        ("brushable_block", "suspicious_gravel"),
        ("skull", "*_skull"),
        ("skull", "*_wall_skull"),
        ("skull", "*_head"),
        ("skull", "*_wall_head"),
        ("mob_spawner", "spawner"),
        ("trial_spawner", "trial_spawner"),
        ("vault", "vault"),
        ("end_portal", "end_portal"),
        ("end_gateway", "end_gateway"),
        ("piston", "moving_piston"),
    ]

    def be_type_for(short):
        for be_name, pattern in be_patterns:
            if be_name not in be_types:
                continue
            if pattern == short or (pattern.startswith("*") and short.endswith(pattern[1:])):
                return be_name
        return None

    out.append("")
    out.append("// BlockEntityForState maps a block state that has a block entity to")
    out.append("// that block entity's type name. A chunk must list one for every such")
    out.append("// block, or the client renders nothing there: a chest with no block")
    out.append("// entity is an invisible chest.")
    out.append("var BlockEntityForState = map[int32]string{")
    be_states = []
    for name, block in sorted(blocks.items()):
        be_name = be_type_for(name.split(":", 1)[1])
        if be_name is None:
            continue
        for st in block.get("states") or []:
            be_states.append((st["id"], be_name))
    for sid, be_name in sorted(be_states):
        out.append(f'\t{sid}: "minecraft:{be_name}",')
    out.append("}")
    # Light. The game keeps both of these in block code, not in any report, so
    # this table is written out by hand from the block classes: the common
    # emitters, and which blocks let light through. Everything not listed as
    # transparent blocks light.
    emissions = {
        "torch": 14, "wall_torch": 14, "soul_torch": 10, "soul_wall_torch": 10,
        "redstone_torch": 7, "redstone_wall_torch": 7,
        "lantern": 15, "soul_lantern": 10, "glowstone": 15, "sea_lantern": 15,
        "shroomlight": 15, "jack_o_lantern": 15, "ochre_froglight": 15,
        "verdant_froglight": 15, "pearlescent_froglight": 15,
        "lava": 15, "fire": 15, "soul_fire": 10, "magma_block": 3,
        "campfire": 15, "soul_campfire": 10, "end_rod": 14, "crying_obsidian": 10,
        "beacon": 15, "conduit": 15, "end_gateway": 15, "end_portal": 15,
        "enchanting_table": 7, "brewing_stand": 1, "brown_mushroom": 1,
        "dragon_egg": 1, "sculk_catalyst": 6, "sculk_sensor": 1,
        "calibrated_sculk_sensor": 1, "sculk_shrieker": 1, "glow_lichen": 7,
        "amethyst_cluster": 5, "large_amethyst_bud": 4, "medium_amethyst_bud": 2,
        "small_amethyst_bud": 1, "light": 15, "candle": 12, "candle_cake": 12,
    }
    # Blocks light passes through. Without shape data this is the honest
    # approximation: exact names plus whole families, never substrings — an
    # earlier version matched "grass" inside "grass_block" and made solid
    # ground transparent.
    transparent_exact = {
        "air", "cave_air", "void_air", "water", "lava", "bubble_column",
        "glass", "tinted_glass", "snow", "vine", "lily_pad", "iron_bars",
        "chain", "light", "frosted_ice", "fire", "soul_fire", "end_rod",
        "cobweb", "structure_void", "barrier", "moss_carpet", "pale_moss_carpet",
        "short_grass", "tall_grass", "fern", "large_fern", "dead_bush",
        "sugar_cane", "nether_sprouts", "warped_roots", "crimson_roots",
        "hanging_roots", "spore_blossom", "azalea", "flowering_azalea",
        "big_dripleaf", "small_dripleaf", "glow_lichen", "sculk_vein",
        "kelp", "seagrass", "tripwire", "string", "flower_pot",
        "amethyst_cluster", "wheat", "carrots", "potatoes", "beetroots",
        # Emitters that are not full blocks: their own cell is see-through.
        "torch", "lantern", "campfire", "brewing_stand", "brown_mushroom",
        "candle", "end_rod", "conduit", "dragon_egg",
    }
    transparent_suffix = (
        "_air", "_glass", "_glass_pane", "_leaves", "_sign", "_hanging_sign",
        "_banner", "_torch", "_lantern", "_campfire", "_button", "_lever",
        "_pressure_plate", "_door", "_trapdoor", "_fence", "_fence_gate",
        "_pane", "_carpet", "_slab", "_stairs", "_bed", "_flower", "_sapling",
        "_bud", "_cluster", "_rail", "_seeds", "_coral", "_coral_fan",
        "_coral_wall_fan", "_roots", "_sprouts", "_vines", "_vine",
        "_mushroom", "_candle", "_cake", "_wall_sign", "_wall_banner",
        "_wall_torch", "_wall_hanging_sign", "_buds",
    )

    def is_transparent(short):
        return short in transparent_exact or short.endswith(transparent_suffix)

    out.append("")
    out.append("// BlockEmission is the light a block state gives off. The game holds")
    out.append("// this in block code, so it is written out here from the block classes;")
    out.append("// it covers the emitters a player meets, not every block in the game.")
    out.append("var BlockEmission = map[int32]int32{")
    emit_states = []
    for name, block in sorted(blocks.items()):
        short = name.split(":", 1)[1]
        level = emissions.get(short)
        if level is None and short.startswith("candle"):
            level = 12
        if level is None and "copper_bulb" in short:
            level = None  # handled per state below: only the lit ones glow
        for st in block.get("states") or []:
            if "copper_bulb" in short:
                lit = (st.get("properties") or {}).get("lit") == "true"
                emit_states.append((st["id"], 15 if lit else 0))
                continue
            if level:
                emit_states.append((st["id"], level))
    for sid, level in sorted(emit_states):
        if level:
            out.append(f"\t{sid}: {level},")
    out.append("}")
    out.append("")
    out.append("// LightOpaque marks the block states that stop light: the ones the")
    out.append("// client renders as opaque, which is what vanilla's")
    out.append("// BlockState.getLightDampening calls isSolidRender. Emitters are NOT")
    out.append("// excluded: vanilla asks whether the shape is a full block, and")
    out.append("// glowstone is, so light does not pass through it — an emitter still")
    out.append("// lights its neighbours, because the step is charged for the block")
    out.append("// being stepped into, not the one being left.")
    out.append("var LightOpaque = map[int32]bool{")
    opaque_states = []
    for name, block in sorted(blocks.items()):
        short = name.split(":", 1)[1]
        if is_transparent(short):
            continue
        for st in block.get("states") or []:
            opaque_states.append(st["id"])
    for sid in sorted(opaque_states):
        out.append(f"\t{sid}: true,")
    out.append("}")
    out.append("")
    out.append("// ItemName maps an item id back to its name, which is how a spawn egg")
    out.append("// knows which mob it holds.")
    out.append("var ItemName = map[int32]string{")
    for name in sorted(items):
        out.append(f'\t{items[name]["protocol_id"]}: "{name}",')
    out.append("}")
    out.append("")
    out.append("// EntityIDs maps an entity type name to its registry id, which is what an")
    out.append("// Add Entity packet carries.")
    out.append("var EntityIDs = map[string]int32{")
    for name, v in sorted(regs.get("minecraft:entity_type", {}).get("entries", {}).items()):
        out.append(f'\t"{name}": {v["protocol_id"]},')
    out.append("}")
    comps = regs.get("minecraft:data_component_type", {}).get("entries", {})
    custom_name = comps.get("minecraft:custom_name", {}).get("protocol_id", 0)
    out.append("")
    out.append("// CustomNameComponent is minecraft:custom_name in the data component")
    out.append("// type registry: what an item renamed at an anvil carries.")
    out.append(f"const CustomNameComponent = {custom_name}")
    banner_patterns = comps.get("minecraft:banner_patterns", {}).get("protocol_id", 0)
    out.append("")
    out.append("// BannerPatternsComponent is minecraft:banner_patterns in the data")
    out.append("// component type registry. A banner carries it as BannerPatternLayers,")
    out.append("// the same codec the block entity's patterns field uses, so the bytes")
    out.append("// travel to the block entity unchanged.")
    out.append(f"const BannerPatternsComponent = {banner_patterns}")
    ent = regs.get("minecraft:entity_type", {}).get("entries", {})
    player_ent = ent.get("minecraft:player", {}).get("protocol_id", 159)
    out.append("")
    out.append("// PlayerEntityTypeID is minecraft:player in the entity_type registry.")
    out.append(f"const PlayerEntityTypeID = {player_ent}")
    bet = regs.get("minecraft:block_entity_type", {}).get("entries", {})
    out.append("")
    out.append("// BlockEntityTypes maps a saved block entity's id to its registry id.")
    out.append("var BlockEntityTypes = map[string]int32{")
    for bname, v in sorted(bet.items()):
        out.append(f'\t"{bname}": {v["protocol_id"]},')
    out.append("}")
    menu = regs.get("minecraft:menu", {}).get("entries", {})

    # Container menus: which blocks open what, how many slots the container
    # half has, and the translation key for the title. Vanilla picks the title
    # per block, so the title lives here rather than being derived from the
    # menu type (a chest and a barrel share generic_9x3 but not their name).
    def menu_id(name, fallback):
        return menu.get("minecraft:" + name, {}).get("protocol_id", fallback)

    kinds = {
        # block name (or prefix) -> (menu type, slots, title key)
        "chest": ("generic_9x3", 27, "container.chest"),
        "trapped_chest": ("generic_9x3", 27, "container.chest"),
        "barrel": ("generic_9x3", 27, "container.barrel"),
        "dispenser": ("generic_3x3", 9, "container.dispenser"),
        "dropper": ("generic_3x3", 9, "container.dropper"),
        "hopper": ("hopper", 5, "container.hopper"),
        "shulker_box": ("shulker_box", 27, "container.shulkerBox"),
        "furnace": ("furnace", 3, "container.furnace"),
        "blast_furnace": ("blast_furnace", 3, "container.blast_furnace"),
        "smoker": ("smoker", 3, "container.smoker"),
        "crafting_table": ("crafting", 10, "container.crafting"),
        "anvil": ("anvil", 3, "container.repair"),
        "chipped_anvil": ("anvil", 3, "container.repair"),
        "damaged_anvil": ("anvil", 3, "container.repair"),
        # A lectern holds one book. The page the client is showing is a
        # container data property, not the slot, so the screen needs the slot
        # contents and a page value.
        "lectern": ("lectern", 1, "container.lectern"),
    }
    out.append("")
    out.append("// ContainerMenus maps a container block state ID to the menu it opens.")
    out.append("var ContainerMenus = map[int32]proto.MenuSpec{")
    state_menus = []
    for name, block in sorted(blocks.items()):
        short = name.split(":", 1)[1]
        spec = kinds.get(short)
        if spec is None and short.endswith("_shulker_box"):
            spec = kinds["shulker_box"]
        if spec is None:
            continue
        kind, slots, title = spec
        mid = menu_id(kind, 0)
        if not mid:
            continue
        for st in block.get("states") or []:
            state_menus.append((st["id"], mid, slots, title))
    for sid, mid, slots, title in sorted(state_menus):
        out.append(f'\t{sid}: {{ID: {mid}, Slots: {slots}, Title: "{title}"}},')
    out.append("}")
    out.append("")
    out.append("// FurnaceLitOn and FurnaceLitOff map a furnace block state to the same")
    out.append("// state with its LIT property flipped, so a cooking furnace can look lit.")
    for var, lit_from, lit_to in (("FurnaceLitOn", "false", "true"), ("FurnaceLitOff", "true", "false")):
        out.append(f"var {var} = map[int32]int32{{")
        pairs = []
        for name, block in sorted(blocks.items()):
            short = name.split(":", 1)[1]
            if short not in ("furnace", "blast_furnace", "smoker"):
                continue
            if "lit" not in (block.get("properties") or {}):
                continue
            # Pair each state with the state that differs only in LIT. Taking a
            # single pair per block (whichever state came last) leaves every
            # other facing unable to light, which is how a placed furnace ends
            # up never looking lit.
            index = {}
            for st in block.get("states") or []:
                props = dict(st.get("properties") or {})
                lit = props.pop("lit", None)
                if lit is None:
                    continue
                index[(tuple(sorted(props.items())), lit)] = st["id"]
            for (props, lit), sid in index.items():
                if lit != lit_from:
                    continue
                other = index.get((props, lit_to))
                if other is not None:
                    pairs.append((sid, other))
        for a, b in sorted(set(pairs)):
            out.append(f"\t{a}: {b},")
        out.append("}")
        out.append("")

    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "items_gen.go").write_text("\n".join(out))
    print(f"wrote {outdir}/items_gen.go: {len(mapping)} placeable items")


if __name__ == "__main__":
    main()
